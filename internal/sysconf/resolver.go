package sysconf

import (
	"strings"
)

// Resolver is what /etc/resolv.conf (or Morche's resolved drop-in) says.
type Resolver struct {
	Servers []string `json:"servers"`
	Search  []string `json:"search"`
	Options []string `json:"options"`
}

// ResolverManager says who writes /etc/resolv.conf: resolved (a link into
// /run/systemd/resolve), resolvconf, networkmanager, or static (a plain file
// people edit by hand).
func ResolverManager(link, text string, nmActive bool) string {
	switch {
	case strings.Contains(link, "systemd/resolve"):
		return "resolved"
	case strings.Contains(link, "resolvconf"):
		return "resolvconf"
	case strings.Contains(text, "Generated by NetworkManager"), nmActive && strings.Contains(text, "NetworkManager"):
		return "networkmanager"
	}
	return "static"
}

func ParseResolvConf(text string) Resolver {
	var r Resolver
	for _, l := range lines(text) {
		f := strings.Fields(l)
		if len(f) < 2 {
			continue
		}
		switch f[0] {
		case "nameserver":
			r.Servers = append(r.Servers, f[1])
		case "search", "domain":
			r.Search = append(r.Search, f[1:]...)
		case "options":
			r.Options = append(r.Options, f[1:]...)
		}
	}
	return r
}

// PrintResolvConf writes r over old: the nameservers, search and options
// lines go where the first of their kind was, everything else stays.
func PrintResolvConf(old string, r Resolver) string {
	var out []string
	done := map[string]bool{}
	put := func(kind string) {
		if done[kind] {
			return
		}
		done[kind] = true
		switch kind {
		case "nameserver":
			for _, s := range r.Servers {
				out = append(out, "nameserver "+s)
			}
		case "search":
			if len(r.Search) > 0 {
				out = append(out, "search "+strings.Join(r.Search, " "))
			}
		case "options":
			if len(r.Options) > 0 {
				out = append(out, "options "+strings.Join(r.Options, " "))
			}
		}
	}
	for _, l := range lines(old) {
		f := strings.Fields(l)
		kind := ""
		if len(f) > 0 {
			kind = f[0]
		}
		switch kind {
		case "nameserver", "options":
			put(kind)
		case "search", "domain":
			put("search")
		default:
			out = append(out, l)
		}
	}
	put("nameserver")
	put("search")
	put("options")
	return join(out)
}

// PrintResolvedDropIn is Morche's systemd-resolved drop-in.
func PrintResolvedDropIn(servers, search []string) string {
	s := "# Written by Morche. Change it from Morche, or remove this file to go back to the defaults.\n[Resolve]\n"
	s += "DNS=" + strings.Join(servers, " ") + "\n"
	if len(search) > 0 {
		s += "Domains=" + strings.Join(search, " ") + "\n"
	}
	return s
}

// ParseResolvedConf reads DNS= and Domains= from a resolved.conf-style file.
func ParseResolvedConf(text string) (servers, search []string) {
	for _, l := range lines(text) {
		k, v, ok := strings.Cut(strings.TrimSpace(l), "=")
		if !ok || strings.HasPrefix(k, "#") {
			continue
		}
		switch strings.TrimSpace(k) {
		case "DNS":
			servers = strings.Fields(v)
		case "Domains":
			search = strings.Fields(v)
		}
	}
	return servers, search
}
