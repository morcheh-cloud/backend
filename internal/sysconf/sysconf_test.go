const hostsText = `127.0.0.1	localhost
127.0.1.1	web-1

# The following lines are desirable for IPv6 capable hosts
::1     ip6-localhost ip6-loopback
ff02::1 ip6-allnodes
10.0.0.5   db.internal db   # primary database
# 10.0.0.6 old-db
192.168.1.9 nas
`

func TestHostsRoundTrip(t *testing.T) {
	entries := ParseHosts(hostsText)
	if got := PrintHosts(hostsText, entries); got != hostsText {
		t.Fatalf("untouched round trip changed the text:\n%s", got)
	}
	if len(entries) != 7 {
		t.Fatalf("want 7 entries, got %d: %+v", len(entries), entries)
	}
	db := entries[4]
	if db.Address != "10.0.0.5" || !slices.Equal(db.Names, []string{"db.internal", "db"}) || db.Comment != "primary database" || !db.Enabled {
		t.Fatalf("db entry: %+v", db)
	}
	old := entries[5]
	if old.Enabled || old.Address != "10.0.0.6" || old.Names[0] != "old-db" {
		t.Fatalf("commented entry: %+v", old)
	}
	if !entries[0].System || !entries[2].System || entries[4].System {
		t.Fatalf("system flags: %+v", entries)
	}

	entries[6].Names = []string{"nas", "nas.lan"}
	got := PrintHosts(hostsText, entries)
	want := strings.Replace(hostsText, "192.168.1.9 nas\n", "192.168.1.9\tnas nas.lan\n", 1)
	if got != want {
		t.Fatalf("one edit:\n%s", got)
	}

	// Removing one and adding one.
	entries = append(slices.Delete(entries, 5, 6), HostEntry{Address: "10.0.0.7", Names: []string{"cache"}, Enabled: true})
	got = PrintHosts(hostsText, entries)
	if strings.Contains(got, "old-db") || !strings.HasSuffix(got, "10.0.0.7\tcache\n") {
		t.Fatalf("remove + add:\n%s", got)
	}
	if !strings.Contains(got, "# The following lines") {
		t.Fatal("a plain comment line was lost")
	}
}

