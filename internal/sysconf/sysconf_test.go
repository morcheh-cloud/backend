func TestHostsSetHostname(t *testing.T) {
	got := SetHostname(hostsText, "web-1", "web-2")
	if !strings.Contains(got, "127.0.1.1\tweb-2\n") || strings.Contains(got, "web-1") {
		t.Fatalf("rename:\n%s", got)
	}
	plain := "127.0.0.1 localhost\n::1 localhost\n"
	got = SetHostname(plain, "old", "new")
	if got != "127.0.0.1 localhost\n127.0.1.1\tnew\n::1 localhost\n" {
		t.Fatalf("added line:\n%q", got)
	}
	// The name also listed elsewhere keeps its other names.
	got = SetHostname("127.0.1.1 web-1.example.com web-1\n", "web-1", "api")
	if got != "127.0.1.1\tapi\n" {
		t.Fatalf("fqdn:\n%q", got)
	}
}

func TestResolverManager(t *testing.T) {
	cases := []struct {
		link, text string
		nm         bool
		want       string
	}{
		{"../run/systemd/resolve/stub-resolv.conf", "nameserver 127.0.0.53\n", false, "resolved"},
		{"/run/systemd/resolve/resolv.conf", "nameserver 1.1.1.1\n", false, "resolved"},
		{"", "# Generated by NetworkManager\nnameserver 10.0.0.1\n", true, "networkmanager"},
		{"/run/resolvconf/resolv.conf", "nameserver 10.0.0.1\n", false, "resolvconf"},
		{"", "nameserver 8.8.8.8\n", false, "static"},
	}
	for _, c := range cases {
		if got := ResolverManager(c.link, c.text, c.nm); got != c.want {
			t.Errorf("%q %q: got %s want %s", c.link, c.text, got, c.want)
		}
	}
}

func TestResolvConfRoundTrip(t *testing.T) {
	text := "# my dns\nnameserver 8.8.8.8\nnameserver 1.1.1.1\nsearch corp.lan\noptions edns0 timeout:2\n"
	r := ParseResolvConf(text)
	if !slices.Equal(r.Servers, []string{"8.8.8.8", "1.1.1.1"}) || !slices.Equal(r.Search, []string{"corp.lan"}) || !slices.Equal(r.Options, []string{"edns0", "timeout:2"}) {
		t.Fatalf("parse: %+v", r)
	}
	if got := PrintResolvConf(text, r); got != text {
		t.Fatalf("untouched:\n%s", got)
	}
	r.Servers = []string{"9.9.9.9"}
	r.Search = nil
	got := PrintResolvConf(text, r)
	if got != "# my dns\nnameserver 9.9.9.9\noptions edns0 timeout:2\n" {
		t.Fatalf("edit:\n%q", got)
	}
	got = PrintResolvedDropIn([]string{"1.1.1.1", "9.9.9.9"}, []string{"corp.lan"})
	if !strings.Contains(got, "[Resolve]\nDNS=1.1.1.1 9.9.9.9\nDomains=corp.lan\n") {
		t.Fatalf("drop-in:\n%s", got)
	}
}

