func TestParseTable(t *testing.T) {
	tb := newTable("user:root", "user", "root", "", `# DO NOT EDIT THIS FILE - edit the master and reinstall.
# (/tmp/crontab.x installed on Sun Nov  1 10:00:00 2026)
# (Cron version -- $Id$)
# m h  dom mon dow   command
MAILTO="ops@example.com"
# Nightly backup
30 2 * * * /backup.sh
#0 4 * * 0 find /tmp -delete

# not a job: just words
@reboot echo up
# Edit this file to introduce tasks
# * * * * * user-name command to be executed
`, true)
	if tb.Content[:4] != "# m " {
		t.Fatalf("header not stripped: %q", tb.Content[:20])
	}
	if len(tb.Env) != 1 || tb.Env[0].Value != "ops@example.com" {
		t.Fatalf("env = %+v", tb.Env)
	}
	want := []CronJob{
		{Line: 3, Name: "Nightly backup", Schedule: "30 2 * * *", User: "root", Command: "/backup.sh", Enabled: true},
		{Line: 4, Name: "", Schedule: "0 4 * * 0", User: "root", Command: "find /tmp -delete", Enabled: false},
		{Line: 7, Name: "not a job: just words", Schedule: "@reboot", User: "root", Command: "echo up", Enabled: true},
	}
	if len(tb.Jobs) != len(want) {
		t.Fatalf("jobs = %+v", tb.Jobs)
	}
	for i, j := range tb.Jobs {
		if j != want[i] {
			t.Errorf("job %d = %+v, want %+v", i, j, want[i])
		}
	}
}

func TestParseSystemTable(t *testing.T) {
	tb := newTable("file:/etc/crontab", "system", "", "/etc/crontab",
		"17 * * * * root cd / && run-parts --report /etc/cron.hourly\n*/5 * * * * www-data php /var/www/cron.php\n", true)
	if len(tb.Jobs) != 2 || tb.Jobs[1].User != "www-data" || tb.Jobs[1].Command != "php /var/www/cron.php" {
		t.Fatalf("jobs = %+v", tb.Jobs)
	}
}

func TestCheckSchedule(t *testing.T) {
	for sched, ok := range map[string]bool{
		"*/15 * * * *":      true,
		"0 9 * * mon-fri":   true,
		"0 0 1 jan,jul *":   true,
		"0 0 * * 7":         true,
		"60 * * * *":        false,
		"0 24 * * *":        false,
		"0 0 0 * *":         false,
		"*/0 * * * *":       false,
		"0 0 * foo *":       false,
		"@daily":            true,
		"1-5/2 1,2,3 * * *": true,
	} {
		if got := checkSchedule(sched) == ""; got != ok {
			t.Errorf("checkSchedule(%q) ok = %v, want %v (%s)", sched, got, ok, checkSchedule(sched))
		}
	}
}

func TestCronCommand(t *testing.T) {
	cmd, in, has := cronCommand(`date +\%F%line one%line two`)
	if cmd != "date +%F" || in != "line one\nline two" || !has {
		t.Fatalf("got %q %q %v", cmd, in, has)
	}
	if _, _, has := cronCommand("echo hi"); has {
		t.Fatal("stdin without %")
	}
}

func TestParseHistory(t *testing.T) {
	now := time.Date(2026, 1, 2, 0, 0, 0, 0, time.UTC)
	h := parseHistory(cronMarker+` clock
1767312000 +0330
`+cronMarker+` file /var/log/syslog
Dec 31 23:59:01 web CRON[12]: (root) CMD (run-parts /etc/cron.hourly)
Jan  1 00:05:01 web CRON[13]: (deploy) CMD (php artisan schedule:run >> /dev/null 2>&1)
Jan  1 00:06:01 web crond[7]: USER root pid 99 cmd echo hi
Jan  1 00:07:01 web CRON[14]: (root) MAIL (mailed 1 byte of output)
`, now)
	if h.Source != "/var/log/syslog" || len(h.Runs) != 3 {
		t.Fatalf("history = %+v", h)
	}
	if r := h.Runs[2]; r.User != "root" || r.Time.Year() != 2025 || r.Time.Hour() != 20 || r.Time.Minute() != 29 {
		t.Errorf("oldest = %+v", r)
	}
	if r := h.Runs[0]; r.Command != "echo hi" {
		t.Errorf("newest = %+v", r)
	}

	h = parseHistory(cronMarker+" journal\n2026-11-01T12:17:01+03:30 host CRON[5]: (root) CMD (cd / && run-parts --report /etc/cron.hourly)\n", now)
	if len(h.Runs) != 1 || h.Runs[0].Time != time.Date(2026, 11, 1, 8, 47, 1, 0, time.UTC) {
		t.Fatalf("journal = %+v", h.Runs)
	}
}

func TestParseTimers(t *testing.T) {
	timers := parseTimers(`Id=apt-daily.timer
Description=Daily apt download activities
Triggers=apt-daily.service
NextElapseUSecRealtime=@1793587531
LastTriggerUSec=@1793500000
ActiveState=active
UnitFileState=enabled
TimersCalendar={ OnCalendar=*-*-* 06,18:00:00 ; next_elapse=@1793587531 }
Result=success
ExecMainStatus=0

Id=apt-daily.service
Description=Daily apt download activities
ActiveState=inactive
UnitFileState=static
Result=exit-code
ExecMainStatus=100
`)
	if len(timers) != 1 {
		t.Fatalf("timers = %+v", timers)
	}
	tm := timers[0]
	if tm.Service != "apt-daily.service" || tm.Result != "exit-code" || tm.ExitStatus != 100 ||
		len(tm.Schedule) != 1 || tm.Schedule[0] != "OnCalendar=*-*-* 06,18:00:00" || tm.Next == nil || tm.Next.Unix() != 1793587531 {
		t.Fatalf("timer = %+v", tm)
	}
}
